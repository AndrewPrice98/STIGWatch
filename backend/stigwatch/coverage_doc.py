"""The coverage tables in docs/COVERAGE.md and the README, generated from the code.

``python -m stigwatch coverage --md`` prints them, ``--write`` updates the committed copies
and ``--check`` (run in CI) fails when they are out of date. Every number comes from the
check engine and the remediation generator; nothing here is typed by hand.

- docs/COVERAGE.md: the full table per benchmark (rules by CAT, how each automated check can
  decide, manual rules, generated remediation).
- README.md: the summary between the ``coverage:start`` / ``coverage:end`` markers.
"""

from __future__ import annotations

from . import benchmarks, config, remediation
from .checks import engine

COVERAGE_DOC = config.REPO_DIR / "docs" / "COVERAGE.md"
README = config.REPO_DIR / "README.md"
START = "<!-- coverage:start (generated by `python -m stigwatch coverage --write`) -->"
END = "<!-- coverage:end -->"
NAMES = {"ubuntu-22.04": "Ubuntu 22.04 LTS", "windows-server-2022": "Windows Server 2022"}
BENCHMARKS = tuple(NAMES)


def _facts(benchmark_id: str) -> dict:
    bench = benchmarks.load_benchmark(benchmark_id)
    cov = engine.coverage(benchmark_id)
    auto = set(remediation.automated_ids(bench))
    cats = {r.stig_id: r.cat for r in bench.rules}
    fix_by_cat = {c: sum(1 for s in auto if cats[s] == c) for c in cov.by_cat}
    return {"bench": bench, "cov": cov, "fix": len(auto), "fix_by_cat": fix_by_cat}


def summary_markdown() -> str:
    lines = ["| Benchmark | Rules | Automated checks | Can decide a result | Manual review | Generated remediation |",
             "|---|---:|---:|---:|---:|---:|"]
    for bid in BENCHMARKS:
        f = _facts(bid)
        cov = f["cov"]
        total = sum(r["total"] for r in cov.by_cat.values())
        decisive = sum(1 for _, _, k in cov.automated if k != "evidence")
        lines.append(f"| {NAMES[bid]} {f['bench'].label} | {total} | {len(cov.automated)} | "
                     f"{decisive} | {len(cov.manual)} | {f['fix']} |")
    return "\n".join(lines) + "\n"


def full_markdown() -> str:
    out = ["# Coverage", "",
           "Generated by `python -m stigwatch coverage --write`; CI fails if it is out of date. "
           "Every number comes from the check engine and the remediation generator.", "",
           "- **Automated**: a declarative check reads collector facts for the rule.",
           "- **full**: the check can return Open and Not a Finding. **partial**: only one of them "
           "(the other outcome is Not Reviewed). **evidence**: neither; it settles Not Applicable "
           "when a fact proves it, otherwise Not Reviewed with the facts shown.",
           "- **Manual**: no check; the rule is Not Reviewed and the check text is shown.",
           "- **Remediation**: rules whose fix can be generated (an Ansible task or a PowerShell step). "
           "Nothing is ever applied by STIGWatch.", ""]
    for bid in BENCHMARKS:
        f = _facts(bid)
        cov = f["cov"]
        out += [f"## {NAMES[bid]} {f['bench'].label}", "",
                "| Severity | Rules | Automated | full | partial | evidence | Manual | Remediation generated |",
                "|---|---:|---:|---:|---:|---:|---:|---:|"]
        tot = dict.fromkeys(("total", "automated", "full", "partial", "evidence", "manual"), 0)
        for cat, row in cov.by_cat.items():
            out.append(f"| {cat} | {row['total']} | {row['automated']} | {row['full']} | {row['partial']} | "
                       f"{row['evidence']} | {row['manual']} | {f['fix_by_cat'][cat]} |")
            for k in tot:
                tot[k] += row[k]
        out.append(f"| **All** | **{tot['total']}** | **{tot['automated']}** | **{tot['full']}** | "
                   f"**{tot['partial']}** | **{tot['evidence']}** | **{tot['manual']}** | **{f['fix']}** |")
        out += ["", "Manual rules: " + (", ".join(s for s, _ in cov.manual) or "none"), ""]
    return "\n".join(out)


def _readme_block() -> str:
    return f"{START}\n{summary_markdown()}{END}"


def _readme_with_block(text: str) -> str:
    a, b = text.find(START), text.find(END)
    if a < 0 or b < a:
        raise ValueError("README.md has no coverage:start / coverage:end markers")
    return text[:a] + _readme_block() + text[b + len(END):]


def stale_files() -> list[str]:
    stale = []
    if not COVERAGE_DOC.exists() or COVERAGE_DOC.read_text(encoding="utf-8") != full_markdown():
        stale.append("docs/COVERAGE.md")
    text = README.read_text(encoding="utf-8")
    if _readme_with_block(text) != text:
        stale.append("README.md")
    return stale


def write() -> None:
    COVERAGE_DOC.parent.mkdir(parents=True, exist_ok=True)
    COVERAGE_DOC.write_text(full_markdown(), encoding="utf-8", newline="\n")
    text = README.read_text(encoding="utf-8")
    README.write_text(_readme_with_block(text), encoding="utf-8", newline="\n")
